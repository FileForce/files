//! Extensions shipped on their own, outside the app: a dynamic library
//! with a small C ABI that speaks JSON, packaged and signed.
//!
//! A package (`.filesext`) is `FILESEXT1\n`, the manifest's length (u32,
//! little endian), the manifest as JSON, then the library. Its `.sig` file is
//! the publisher's Ed25519 signature of the whole package
//! ([`crate::package`]). Files reads and checks the manifest and the
//! signature *before* loading anything, and loads a Pro plugin only when
//! the license covers it, so unlicensed code never runs.
//!
//! Writing one: implement [`Plugin`], then `files_sdk::export_plugin!(MyPlugin);`
//! in a `cdylib` crate, and `cargo xtask package-extension <crate>`.

use serde::{Deserialize, Serialize};

use crate::{Context, Outcome};

/// Bumped when the functions below change.
pub const ABI_VERSION: u32 = 1;
const MAGIC: &[u8] = b"FILESEXT1\n";

/// A menu item a plugin adds (owned: it crosses the library boundary).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct PluginMenuItem {
    pub command: String,
    pub title: String,
    /// `file`, `folder`, `background` (any mix).
    pub targets: Vec<String>,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct PluginManifest {
    pub id: String,
    pub name: String,
    pub version: String,
    pub summary: String,
    pub publisher: String,
    /// `None`: free; otherwise the license product that unlocks it.
    pub product: Option<String>,
    /// Permission keys (see [`crate::Permission::key`]).
    pub permissions: Vec<String>,
    pub menu: Vec<PluginMenuItem>,
    pub menu_color: Option<String>,
    pub abi: u32,
}

/// What a plugin implements.
pub trait Plugin: Sync {
    fn manifest(&self) -> PluginManifest;
    fn run(&self, command: &str, context: &Context) -> Result<Outcome, String>;
}

/// Builds a `.filesext` package.
pub fn pack(manifest: &PluginManifest, library: &[u8]) -> Result<Vec<u8>, String> {
    let json = serde_json::to_vec(manifest).map_err(|error| error.to_string())?;
    let mut bytes = MAGIC.to_vec();
    bytes.extend((json.len() as u32).to_le_bytes());
    bytes.extend(json);
    bytes.extend(library);
    Ok(bytes)
}

/// Splits a package into its manifest and library without running anything.
pub fn unpack(bytes: &[u8]) -> Result<(PluginManifest, &[u8]), String> {
    let rest = bytes.strip_prefix(MAGIC).ok_or("not a Files extension package")?;
    let (length, rest) = rest.split_at_checked(4).ok_or("truncated package")?;
    let length = u32::from_le_bytes(length.try_into().expect("4 bytes")) as usize;
    let (json, library) = rest.split_at_checked(length).ok_or("truncated package")?;
    let manifest: PluginManifest = serde_json::from_slice(json).map_err(|error| format!("bad manifest: {error}"))?;
    if manifest.abi != ABI_VERSION {
        return Err(format!("built for extension ABI {}, this Files speaks {ABI_VERSION}: update Files or the extension", manifest.abi));
    }
    Ok((manifest, library))
}

/// The functions a plugin library exports (generated by [`export_plugin!`]).
pub mod abi {
    use std::ffi::{CStr, CString, c_char};

    pub type AbiVersion = unsafe extern "C" fn() -> u32;
    pub type ManifestJson = unsafe extern "C" fn() -> *mut c_char;
    /// `(command, context JSON) → {"ok": Outcome} | {"error": "…"}`.
    pub type Run = unsafe extern "C" fn(*const c_char, *const c_char) -> *mut c_char;
    pub type Free = unsafe extern "C" fn(*mut c_char);

    pub fn into_raw(text: String) -> *mut c_char {
        CString::new(text.replace('\0', "")).expect("no NUL").into_raw()
    }

    /// # Safety
    /// `pointer` must be a NUL-terminated string valid for the call.
    pub unsafe fn read(pointer: *const c_char) -> String {
        if pointer.is_null() {
            return String::new();
        }
        unsafe { CStr::from_ptr(pointer) }.to_string_lossy().into_owned()
    }

    /// # Safety
    /// `pointer` must come from [`into_raw`].
    pub unsafe fn free(pointer: *mut c_char) {
        if !pointer.is_null() {
            drop(unsafe { CString::from_raw(pointer) });
        }
    }
}

/// Exports a [`Plugin`] from a `cdylib`.
#[macro_export]
macro_rules! export_plugin {
    ($plugin:expr) => {
        #[unsafe(no_mangle)]
        pub extern "C" fn files_plugin_abi() -> u32 {
            $crate::plugin::ABI_VERSION
        }

        #[unsafe(no_mangle)]
        pub extern "C" fn files_plugin_manifest() -> *mut std::ffi::c_char {
            let manifest = $crate::plugin::Plugin::manifest(&$plugin);
            $crate::plugin::abi::into_raw(serde_json::to_string(&manifest).unwrap_or_default())
        }

        /// # Safety
        /// Both pointers are NUL-terminated strings from the host.
        #[unsafe(no_mangle)]
        pub unsafe extern "C" fn files_plugin_run(command: *const std::ffi::c_char, context: *const std::ffi::c_char) -> *mut std::ffi::c_char {
            let command = unsafe { $crate::plugin::abi::read(command) };
            let context: $crate::Context = serde_json::from_str(&unsafe { $crate::plugin::abi::read(context) }).unwrap_or_default();
            let reply = match $crate::plugin::Plugin::run(&$plugin, &command, &context) {
                Ok(outcome) => serde_json::json!({ "ok": outcome }),
                Err(error) => serde_json::json!({ "error": error }),
            };
            $crate::plugin::abi::into_raw(reply.to_string())
        }

        /// # Safety
        /// `text` comes from this library.
        #[unsafe(no_mangle)]
        pub unsafe extern "C" fn files_plugin_free(text: *mut std::ffi::c_char) {
            unsafe { $crate::plugin::abi::free(text) }
        }
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn packages_round_trip_and_reject_other_abis() {
        let mut manifest = PluginManifest {
            id: "demo".into(),
            name: "Demo".into(),
            version: "1.0.0".into(),
            summary: String::new(),
            publisher: "Files".into(),
            product: Some("demo".into()),
            permissions: vec![],
            menu: vec![],
            menu_color: None,
            abi: ABI_VERSION,
        };
        let package = pack(&manifest, b"LIBRARY").unwrap();
        let (read, library) = unpack(&package).unwrap();
        assert_eq!((read, library), (manifest.clone(), &b"LIBRARY"[..]));
        manifest.abi = 99;
        assert!(unpack(&pack(&manifest, b"x").unwrap()).unwrap_err().contains("ABI"));
        assert!(unpack(b"zip bytes").is_err());
        assert!(unpack(b"FILESEXT1\n\xff\xff\xff\xff{").is_err(), "lengths past the end are refused");
    }
}
